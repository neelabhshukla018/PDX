"""Comprehensive End-to-End Automated Verification Test Suite for RogeX RAG.
Tests PDF extraction, LangChain chunking, Sentence Transformers, FAISS,
Retrieval, Multi-Document indexing, Provenance attribution, Document removal,
and Refusal behavior.
"""

import os
import sys
from pathlib import Path

# Add project root to path
sys.path.insert(0, str(Path(__file__).resolve().parent))

import fitz  # PyMuPDF for creating realistic synthetic PDF fixtures
from rag import (
    DEFAULT_CHUNK_OVERLAP,
    DEFAULT_CHUNK_SIZE,
    STRICT_REFUSAL_MESSAGE,
    DocumentChunk,
    DocumentTextSplitter,
    EmbeddingManager,
    ExtractedPage,
    FAISSVectorStore,
    PDFProcessor,
    ProcessedDocument,
    RAGEngine,
    RAGResponse,
    get_embedding_manager,
)


def create_sample_pdf(pdf_path: Path, title: str, domain: str):
    """Generate a realistic 3-page academic research PDF for testing."""
    doc = fitz.open()

    # Page 1: Abstract and Overview
    p1 = doc.new_page()
    text_p1 = (
        f"Title: {title}\n"
        f"Domain: {domain}\n\n"
        "Abstract:\n"
        "This research paper evaluates the performance of Retrieval-Augmented Generation (RAG) "
        "applied to enterprise and academic document intelligence. We propose RogeX, an advanced system "
        "integrating FAISS vector databases with local dense bi-encoders and Google Gemini LLMs. "
        "Empirical benchmarks demonstrate a 98.4% precision in source attribution.\n\n"
        "1. Executive Summary\n"
        "Traditional Large Language Models frequently suffer from factual hallucinations when operating "
        "outside their training corpus. RogeX addresses this challenge by combining dense vector retrieval "
        "with strict prompt grounding rules. If a user asks about topics not explicitly covered in the uploaded "
        "excerpts, the system strictly returns a grounded refusal token."
    )
    p1.insert_text((50, 72), text_p1, fontsize=11)

    # Page 2: Architecture & Indexing
    p2 = doc.new_page()
    text_p2 = (
        "2. Technical Architecture and Indexing Methodology\n\n"
        "2.1 Vector Representation\n"
        "The RogeX vector store utilizes FAISS IndexFlatIP (Inner Product) on L2-normalized 384-dimensional embeddings "
        "generated by the all-MiniLM-L6-v2 transformer model. Normalization ensures that inner product computations correspond "
        "strictly to cosine similarity, with an operational similarity threshold theta = 0.20.\n\n"
        "2.2 Hierarchical Chunking\n"
        "Documents undergo recursive character segmentation using LangChain's RecursiveCharacterTextSplitter with a default "
        "chunk size of 1000 characters and 200 characters overlap. Metadata preservation tracks the source document filename, "
        "page indices, and unique chunk IDs across all pipeline stages."
    )
    p2.insert_text((50, 72), text_p2, fontsize=11)

    # Page 3: Evaluation Metrics
    p3 = doc.new_page()
    text_p3 = (
        "3. Experimental Results and Quantitative Benchmarks\n\n"
        "Evaluation across 500 test queries yielded a mean retrieval latency of 14 milliseconds and 0% hallucination rate "
        "under strict refusal constraints. The overall accuracy reached 96.8% across technical documentation benchmarks.\n\n"
        "4. Conclusion and Future Directions\n"
        "RogeX demonstrates that local embeddings paired with FAISS IndexFlatIP provide sub-20ms retrieval times "
        "while ensuring absolute privacy for local documents."
    )
    p3.insert_text((50, 72), text_p3, fontsize=11)

    doc.save(str(pdf_path))
    doc.close()


def run_all_tests():
    print("=" * 70)
    print("STARTING ROGEX COMPREHENSIVE RAG PIPELINE VERIFICATION")
    print("=" * 70)

    data_dir = Path(__file__).resolve().parent / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    pdf1_path = data_dir / "test_doc_alpha.pdf"
    pdf2_path = data_dir / "test_doc_beta.pdf"

    create_sample_pdf(pdf1_path, "Project RogeX Alpha", "Computer Science & AI")
    create_sample_pdf(pdf2_path, "Project RogeX Beta", "Quantum & High Performance Computing")
    print(f"✓ Synthetic test documents generated:\n  - {pdf1_path.name}\n  - {pdf2_path.name}")

    # --------------------------------------------------------------------------
    # TEST 1: PDF Text Extraction & Metadata Preservation
    # --------------------------------------------------------------------------
    print("\n[TEST 1] PDF Ingestion & Text Extraction (PyPDF)...")
    doc1 = PDFProcessor.extract_from_path(pdf1_path)
    assert doc1.error is None, f"Extraction failed: {doc1.error}"
    assert doc1.total_pages == 3, f"Expected 3 pages, got {doc1.total_pages}"
    assert doc1.total_characters > 800, f"Expected >800 chars, got {doc1.total_characters}"
    assert not doc1.is_empty, "Document incorrectly marked as empty"
    assert doc1.pages[0].page_number == 1, "Page number 1 incorrect"
    assert doc1.pages[1].page_number == 2, "Page number 2 incorrect"
    assert doc1.pages[2].page_number == 3, "Page number 3 incorrect"
    print(f"  ✓ Successfully extracted '{doc1.filename}': {doc1.total_pages} pages, {doc1.total_characters} chars")

    # --------------------------------------------------------------------------
    # TEST 2: Empty and Corrupted PDF Handling
    # --------------------------------------------------------------------------
    print("\n[TEST 2] Error Handling: Empty and Corrupted Files...")
    empty_doc = PDFProcessor.extract_from_bytes(b"", "empty_file.pdf")
    assert empty_doc.is_empty, "Empty bytes should be detected as empty"
    assert "empty" in empty_doc.error.lower(), "Expected empty error message"

    corrupted_doc = PDFProcessor.extract_from_bytes(b"NOT_A_REAL_PDF_HEADER", "corrupted.pdf")
    assert corrupted_doc.error is not None, "Corrupted bytes should trigger error"
    print("  ✓ Gracefully handled empty bytes and corrupted files.")

    # --------------------------------------------------------------------------
    # TEST 3: Document Chunking (LangChain Recursive Splitter)
    # --------------------------------------------------------------------------
    print("\n[TEST 3] LangChain Document Chunking & Provenance Tracking...")
    splitter = DocumentTextSplitter(chunk_size=500, chunk_overlap=100)
    chunks1 = splitter.split_processed_document(doc1)
    assert len(chunks1) >= 3, f"Expected >= 3 chunks, got {len(chunks1)}"

    # Verify provenance metadata
    for c in chunks1:
        assert c.source == doc1.filename, "Chunk source mismatch"
        assert c.page in [1, 2, 3], "Chunk page number invalid"
        assert len(c.text) > 0, "Empty chunk text"
        assert "doc_id" in c.metadata, "Metadata missing doc_id"
    print(f"  ✓ Generated {len(chunks1)} chunks with full provenance (source, page, char_count)")

    # --------------------------------------------------------------------------
    # TEST 4: HuggingFace Sentence Transformers Local Embeddings
    # --------------------------------------------------------------------------
    print("\n[TEST 4] Sentence Transformers Embedding Engine...")
    embedder = get_embedding_manager("sentence-transformers/all-MiniLM-L6-v2")
    assert embedder.dimension == 384, f"Expected 384 dimensions, got {embedder.dimension}"

    sample_texts = [c.text for c in chunks1[:3]]
    batch_embeddings = embedder.embed_texts(sample_texts)
    assert batch_embeddings.shape == (3, 384), f"Unexpected batch shape: {batch_embeddings.shape}"

    # Verify unit L2 normalization (norm should be ~1.0)
    norms = [float(sum(v ** 2) ** 0.5) for v in batch_embeddings]
    for norm in norms:
        assert abs(norm - 1.0) < 1e-4, f"Embeddings not unit normalized: norm={norm}"
    print(f"  ✓ Embeddings verified: dimension={embedder.dimension}, L2-normalized=True")

    # --------------------------------------------------------------------------
    # TEST 5: FAISS Vector Indexing & Similarity Search
    # --------------------------------------------------------------------------
    print("\n[TEST 5] FAISS Vector Store Indexing & Similarity Search...")
    vstore = FAISSVectorStore(dimension=embedder.dimension)
    vstore.clear()
    assert vstore.is_empty(), "Vector store should be empty initially"

    indexed = vstore.add_chunks(chunks1, embedder)
    assert indexed == len(chunks1), f"Expected {len(chunks1)}, indexed {indexed}"
    assert vstore.total_vectors == len(chunks1), "Total vectors mismatch"

    # Search for specific architecture query
    query = "What is the vector index algorithm and embedding dimension?"
    hits = vstore.similarity_search(query, top_k=3, embedding_manager=embedder)
    assert len(hits) > 0, "No search hits returned"
    top_hit = hits[0]
    print(f"  ✓ Search Top Hit: '{top_hit.source}' (Page {top_hit.page}, Score: {top_hit.score:.4f})")
    assert "IndexFlatIP" in top_hit.text or "384" in top_hit.text or "all-MiniLM-L6-v2" in top_hit.text, (
        f"Search hit does not contain expected concepts. Found:\n{top_hit.text}"
    )

    # --------------------------------------------------------------------------
    # TEST 6: Multiple PDF Support (Concurrent Indexing)
    # --------------------------------------------------------------------------
    print("\n[TEST 6] Multiple Document Ingestion & Cross-Document Search...")
    doc2 = PDFProcessor.extract_from_path(pdf2_path)
    chunks2 = splitter.split_processed_document(doc2)
    vstore.add_chunks(chunks2, embedder)

    stats = vstore.get_stats()
    assert stats["total_documents"] == 2, f"Expected 2 documents, got {stats['total_documents']}"
    assert vstore.total_vectors == len(chunks1) + len(chunks2)
    print(f"  ✓ Multi-document store active: {stats['total_documents']} documents, {vstore.total_vectors} total vectors")

    # Search across documents
    cross_hits = vstore.similarity_search("What is evaluated in this research?", top_k=4, embedding_manager=embedder)
    sources_in_hits = set(h.source for h in cross_hits)
    print(f"  ✓ Sources represented in top hits: {sources_in_hits}")

    # --------------------------------------------------------------------------
    # TEST 7: Document Removal & Dynamic Index Rebuilding
    # --------------------------------------------------------------------------
    print("\n[TEST 7] Document Removal & Index Rebuilding...")
    removed_count = vstore.remove_document(doc1.filename, embedder)
    assert removed_count == len(chunks1), f"Expected {len(chunks1)} removed, got {removed_count}"
    assert vstore.total_vectors == len(chunks2), f"Expected {len(chunks2)} remaining, got {vstore.total_vectors}"

    remaining_stats = vstore.get_stats()
    assert doc1.filename not in remaining_stats["documents"], f"'{doc1.filename}' should not be in store"
    assert doc2.filename in remaining_stats["documents"], f"'{doc2.filename}' should remain in store"
    print(f"  ✓ Successfully removed '{doc1.filename}'. Remaining vectors: {vstore.total_vectors}")

    # Re-add doc1 for subsequent RAG tests
    vstore.add_chunks(chunks1, embedder)

    # --------------------------------------------------------------------------
    # TEST 8: FAISS Persistence (Save & Load)
    # --------------------------------------------------------------------------
    print("\n[TEST 8] FAISS Index Persistence (Save to Disk & Load)...")
    save_path = data_dir / "test_vectorstore"
    assert vstore.save(save_path), "Failed to save FAISS index"
    assert (save_path / "index.faiss").exists(), "index.faiss does not exist"
    assert (save_path / "metadata.json").exists(), "metadata.json does not exist"

    loaded_store = FAISSVectorStore(dimension=embedder.dimension)
    assert loaded_store.load(save_path), "Failed to load FAISS index"
    assert loaded_store.total_vectors == vstore.total_vectors, "Vector count mismatch after reload"
    print(f"  ✓ Persistence confirmed: Saved and reloaded {loaded_store.total_vectors} vectors.")

    # --------------------------------------------------------------------------
    # TEST 9: Strict Grounding & Refusal Logic
    # --------------------------------------------------------------------------
    print("\n[TEST 9] Strict RAG Grounding & Refusal Engine...")
    rag = RAGEngine(vector_store=vstore)

    # Out of domain query -> Should refuse with exact refusal phrase
    out_of_domain = "What is the recipe for baking chocolate chip cookies?"
    resp_ood = rag.query(out_of_domain, top_k=4, similarity_threshold=0.35)
    print(f"  Query: '{out_of_domain}'")
    print(f"  Response Status: {resp_ood.status}")
    print(f"  Response Answer: {resp_ood.answer}")
    assert resp_ood.status == "insufficient_info", f"Expected insufficient_info, got {resp_ood.status}"
    assert resp_ood.answer == STRICT_REFUSAL_MESSAGE, f"Expected exact refusal message, got: {resp_ood.answer}"
    print(f"  ✓ Strict refusal token verified: '{STRICT_REFUSAL_MESSAGE}'")

    # In-domain query retrieval test
    in_domain = "What is the mean retrieval latency reported in the benchmarks?"
    results, citations, direct_ans = rag.retrieve(in_domain, top_k=4)
    assert len(results) > 0, "Failed to retrieve relevant chunks for in-domain query"
    assert len(citations) > 0, "Failed to build citations"
    print(f"  ✓ Retrieved {len(citations)} citations for: '{in_domain}'")
    for c in citations[:2]:
        print(f"    - Source: {c.source}, Page: {c.page}, Match: {c.score:.2f}")

    # --------------------------------------------------------------------------
    # TEST 10: Gemini API Configuration Handling
    # --------------------------------------------------------------------------
    print("\n[TEST 10] Gemini API Key Missing & Configuration Handling...")
    # Engine without API key should clearly indicate key required without crashing
    unconfigured_rag = RAGEngine(vector_store=vstore, api_key="")
    assert not unconfigured_rag.is_configured(), "Should report unconfigured"
    unconf_resp = unconfigured_rag.query("What is RogeX?", top_k=2)
    assert unconf_resp.status == "api_key_missing", f"Expected api_key_missing, got {unconf_resp.status}"
    assert "Gemini API Key Required" in unconf_resp.answer, "Expected key required guidance"
    print("  ✓ Unconfigured state returned clear user guidance without crashing.")

    # --------------------------------------------------------------------------
    # TEST 11: Cleanup Test Artifacts
    # --------------------------------------------------------------------------
    try:
        pdf1_path.unlink(missing_ok=True)
        pdf2_path.unlink(missing_ok=True)
    except Exception:
        pass

    print("\n" + "=" * 70)
    print("ALL 10 COMPREHENSIVE RAG PIPELINE TESTS PASSED WITH 100% SUCCESS!")
    print("=" * 70)


if __name__ == "__main__":
    run_all_tests()
